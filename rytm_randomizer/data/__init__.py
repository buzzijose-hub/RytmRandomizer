"""Shared canonical data layer for RytmRandomizer.

This sub-package is the single source of truth for every piece of V1.34
domain data: per-machine parameter maps, anchor states, safe limits, deltas,
zone definitions, the profile registry, scene/preset definitions, the four-pad
group layout, and the intensity / page / per-pad mode mutation plans.

Both codebases import their data from here:

* ``rytm_hybrid_randomizer_v134`` (the monolith) imports these names instead of
  defining the dicts inline.
* The ``rytm_randomizer`` package modules (``profiles``, ``scenes``,
  ``constants``) re-export from here instead of hand-re-typing subsets.

Because there is exactly one copy of every value, the two codebases can never
drift apart. ``tests/test_data_layer.py`` is a drift-guard that fails loudly if
the data is ever changed in a way that breaks known-good expectations.
"""

