"""Passive controller-brain mapping profiles for 16-encoder surfaces.

This data module defines reviewable controller intent pages. It deliberately
does not model raw MIDI controller ports, raw CC numbers, MIDI input, LED
feedback, or active hardware behavior. A future armed input bridge can consume
these facts and translate physical controls into existing RytmRandomizer
commands.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from types import MappingProxyType
from typing import Final


@dataclass(frozen=True)
class ControllerMappingControlSpec:
    """One stable slot on a 16-control page."""

    slot: int
    label: str
    target_device: str
    target_scope: str
    intent_key: str
    action: str
    lane: str
    safety_tier: str
    recovery_action: str
    notes: str


@dataclass(frozen=True)
class ControllerMappingPageSpec:
    """One controller page with exactly sixteen control slots."""

    key: str
    label: str
    summary: str
    controls: tuple[ControllerMappingControlSpec, ...]


@dataclass(frozen=True)
class ControllerMappingProfileSpec:
    """One passive controller-brain profile for future hardware surfaces."""

    key: str
    label: str
    controller_family: str
    controller_layout: str
    encoder_count: int
    pages: tuple[ControllerMappingPageSpec, ...]
    safety_summary: str
    blocked_active_actions: tuple[str, ...]


CONTROLLER_ENCODER_COUNT: Final[int] = 16
DEFAULT_CONTROLLER_MAPPING_PROFILE: Final[str] = "generic-16-encoder-performance"

_SAFETY_SUMMARY: Final[str] = (
    "passive mapping only; translates controller gestures into reviewed "
    "RytmRandomizer intent, not active MIDI sends"
)
_BLOCKED_ACTIVE_ACTIONS: Final[tuple[str, ...]] = (
    "open MIDI controller input",
    "MIDI learn or raw CC capture",
    "send controller feedback",
    "open Analog Rytm output",
    "open Analog Four output",
    "arm hardware",
    "send hardware MIDI",
    "mutate a snapshot",
    "dispatch Cockpit WebSocket commands",
)


def _controller_control(
    slot: int,
    label: str,
    target_device: str,
    target_scope: str,
    intent_key: str,
    action: str,
    lane: str,
    safety_tier: str,
    recovery_action: str,
    notes: str,
) -> ControllerMappingControlSpec:
    return ControllerMappingControlSpec(
        slot=slot,
        label=label,
        target_device=target_device,
        target_scope=target_scope,
        intent_key=intent_key,
        action=action,
        lane=lane,
        safety_tier=safety_tier,
        recovery_action=recovery_action,
        notes=notes,
    )


def _page(
    key: str,
    label: str,
    summary: str,
    controls: tuple[ControllerMappingControlSpec, ...],
) -> ControllerMappingPageSpec:
    if len(controls) != CONTROLLER_ENCODER_COUNT:
        raise ValueError(f"controller page {key!r} must define 16 controls")
    expected_slots = tuple(range(1, CONTROLLER_ENCODER_COUNT + 1))
    actual_slots = tuple(control.slot for control in controls)
    if actual_slots != expected_slots:
        raise ValueError(f"controller page {key!r} slots must be 1-16")
    return ControllerMappingPageSpec(
        key=key,
        label=label,
        summary=summary,
        controls=controls,
    )


